// Runs every registered setup over data/history and writes research/results.json and research/RESULTS.md.
// Usage: npm run backtest
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { STRATEGIES } from '../server/strategies/index.js';
import { manage, COST_POINTS } from '../server/strategies/common.js';
import { loadHistory, tradingDates } from './history.js';
import { summary, inPeriod, dollars, benchmark, judge, label } from './stats.js';

const here = path.dirname(fileURLToPath(import.meta.url));
export const PERIODS = { tune: ['2019-01-01', '2023-12-31'], judge: ['2024-01-01', '2026-12-31'], last12: ['2025-10-22', '2026-10-21'] };

/** Every closed trade a setup takes over the history, oldest first. */
export function runStrategy(hist, strat) {
  const trades = [];
  for (const { key, contract } of tradingDates(hist)) {
    const res = strat.evaluate(contract.ctx, key);
    const t = res.trade;
    if (!t || t.status === 'open') continue;
    // Same entry bar, same stop distance, same exits, both directions: feeds the random-direction benchmark.
    const flip = (dir) => manage(contract.ctx, { ...t, dir, stop: t.entry - dir * t.risk, target: strat.targetR ? t.entry + dir * strat.targetR * t.risk : null }, res.times.flat).r;
    trades.push({ key, contract: contract.code, dir: t.dir, signalT: t.signalT, entry: t.entry, stop: t.stop, risk: t.risk, target: t.target, status: t.status, exitPx: t.exitPx, exitT: t.exitT, r: t.r, long: flip(1), short: flip(-1) });
  }
  return trades;
}

export function report(strat, trades) {
  const tune = summary(inPeriod(trades, ...PERIODS.tune)), jt = inPeriod(trades, ...PERIODS.judge), j = summary(jt);
  const last12 = summary(inPeriod(trades, ...PERIODS.last12));
  const years = {};
  for (const t of trades) (years[t.key.slice(0, 4)] ||= []).push(t);
  for (const y of Object.keys(years)) years[y] = summary(years[y]);
  const judgeYears = Object.entries(years).filter(([y]) => y >= '2024').sort((a, b) => b[1].totalR - a[1].totalR);
  const best = judgeYears[0]?.[0] ?? null;
  const withoutBest = { year: best, ...summary(jt.filter(t => t.key.slice(0, 4) !== best)) };
  const dollar = dollars(jt), bench = benchmark(jt.map(t => ({ long: t.long, short: t.short })));
  const rules = judge({ judge: j, years, last12, dollar });
  return { id: strat.id, code: strat.code, name: strat.name, window: strat.window, source: strat.source, label: label(rules, tune, j), rules, tune, judge: j, last12, years, withoutBest, dollar, benchmark: bench, all: summary(trades) };
}

const f = (x, d = 2) => (x == null ? 'n/a' : (x >= 0 ? '+' : '') + x.toFixed(d));
const n = (x, d = 1) => (x == null ? 'n/a' : x.toFixed(d));
const money = (x) => (x < 0 ? '-$' : '$') + Math.abs(Math.round(x)).toLocaleString('en-US');

export function markdown(reports, hist) {
  const L = [];
  L.push('# Results: The Desk strategy tests', '', `Generated by \`npm run backtest\` from ${hist.meta.bars.toLocaleString('en-US')} NQ 15-minute bars, ${hist.start} to ${hist.end}.`, 'Rules and the pass bar were fixed first in `research/PREREGISTRATION.md`. 1 NQ point cost per trade, entries on closed bars, stop-first.', '', 'No setup is promised to win. This is the fair test and what it found.', '');
  L.push('## Verdicts (judge period: 2024-01-01 to ' + hist.end + ')', '', '| Setup | Window | Verdict | Trades | Win % | Avg R | t-stat | Worst drawdown | Rules met |', '|---|---|---|---|---|---|---|---|---|');
  for (const r of reports) L.push(`| ${r.code} ${r.name} | ${r.window} | **${r.label}** | ${r.judge.trades} | ${n(r.judge.win)} | ${f(r.judge.avgR, 3)} | ${n(r.judge.t, 2)} | ${n(r.judge.maxDD)}R, ${money(r.dollar.maxDD)} | ${r.rules.filter(x => x.ok).length} of 6 |`);
  L.push('', 'Dollar drawdown is on MNQ at $250 risk with whole contracts; signals whose stop is too wide for one contract are skipped.', '');
  for (const r of reports) {
    L.push(`## ${r.code} ${r.name}: ${r.label}`, '', `Source: ${r.source}.`, '', '| Period | Trades | Win % | Avg R | t-stat | Worst drawdown |', '|---|---|---|---|---|---|');
    for (const [nm, s] of [['2019-2023 (look-at)', r.tune], ['2024 on (judge)', r.judge], ['Last 12 months', r.last12], [`Judge period without its best year (${r.withoutBest.year})`, r.withoutBest]]) L.push(`| ${nm} | ${s.trades} | ${n(s.win)} | ${f(s.avgR, 3)} | ${n(s.t, 2)} | ${n(s.maxDD)}R |`);
    L.push('', 'By year: ' + Object.entries(r.years).sort().map(([y, s]) => `${y} ${f(s.avgR, 3)} (${s.trades})`).join(', ') + '.', '');
    L.push(`Random-direction benchmark (same entries and stops, 500 runs): average ${f(r.benchmark.mean, 3)}R, 95th percentile ${f(r.benchmark.p95, 3)}R. The setup made ${f(r.judge.avgR, 3)}R.`, '');
    L.push(`On the account: median stop ${n(r.dollar.medianStop, 0)} NQ points. ${n(r.dollar.fitPct, 0)}% of signals fit $250 on at least 1 MNQ (${r.dollar.taken} of ${r.dollar.signals}). Those trades: net ${money(r.dollar.net)}, worst drawdown ${money(r.dollar.maxDD)} against the $2,000 limit.`, '');
    L.push('Pass rules:', ...r.rules.map(x => `- ${x.ok ? 'met' : '**missed**'}: ${x.rule}`), '');
  }
  return L.join('\n');
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const hist = loadHistory();
  const reports = STRATEGIES.map(s => report(s, runStrategy(hist, s)));
  const out = { generated: new Date().toISOString(), data: { start: hist.start, end: hist.end, bars: hist.meta.bars }, cost: COST_POINTS, periods: PERIODS, strategies: reports };
  fs.writeFileSync(path.join(here, 'results.json'), JSON.stringify(out, null, 1));
  fs.writeFileSync(path.join(here, 'RESULTS.md'), markdown(reports, hist) + fs.readFileSync(path.join(here, 'NOTES.md'), 'utf8'));
  for (const r of reports) console.log(`${r.code} ${r.name.padEnd(26)} ${r.label.padEnd(22)} judge ${String(r.judge.trades).padStart(4)} trades  ${f(r.judge.avgR, 3)}R  t ${n(r.judge.t, 2)}  DD ${n(r.judge.maxDD)}R  | 2019-23 ${f(r.tune.avgR, 3)}R (${r.tune.trades})`);
}
